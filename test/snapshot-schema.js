/**
 * Writes test/schema.sql: the SCHEMA ONLY (no rows) of the dev database, which
 * the e2e database is built from before the app boots and re-applies every
 * migration on top (the runner re-runs all of them on each boot).
 *
 * Why a snapshot and not "migrations from empty": an empty database cannot be
 * built from migrations alone today. The tenancy and RBAC changes were applied
 * by one-off scripts (scripts/migrate-tenancy.mjs, migrate-rbac.mjs) between
 * migrations, and later migrations depend on what they created (e.g. 0017
 * needs UNIQUE (organization_id, id) on users). Regenerate after a schema
 * change that a migration does not cover:  npm run e2e:schema
 */
require('dotenv').config({ path: require('node:path').join(__dirname, '..', '.env'), quiet: true });
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const src = process.env.DATABASE_URL;
if (!src) throw new Error('DATABASE_URL missing in server/.env');
const bin = ['/usr/lib/postgresql/18/bin/pg_dump', 'pg_dump'].find((b) => b === 'pg_dump' || fs.existsSync(b));
let sql = execFileSync(bin, ['--schema-only', '--no-owner', '--no-privileges', '--schema=public', src], { maxBuffer: 64 * 1024 * 1024 }).toString();
// Strip session settings that pin a server-specific value, and psql meta-commands.
sql = sql
  .split('\n')
  .filter((l) => !/^\\(restrict|unrestrict)\b/.test(l) && !/^SET transaction_timeout/.test(l))
  .join('\n');
fs.writeFileSync(path.join(__dirname, 'schema.sql'), `-- Generated by test/snapshot-schema.js from the dev database (schema only, no data).\n-- Regenerate: npm run e2e:schema\n${sql}`);
console.log(`test/schema.sql written (${sql.split('\n').length} lines)`);
